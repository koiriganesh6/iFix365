import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { requireAdmin } from '../middleware/auth.js';
import { login, list, setStatus, remove } from '../controllers/admin.js';
const r = Router();
r.post('/login', rateLimit({ windowMs: 15 * 60 * 1000, max: 10 }), login);
r.get('/repairs', requireAdmin, list);
r.patch('/repairs/:id', requireAdmin, setStatus);
r.delete('/repairs/:id', requireAdmin, remove);
export default r;
